"""Install the pinned Specify CLI locally; never initialize or update project files."""

import argparse
import os
from pathlib import Path
import subprocess
import sys
import venv
from tempfile import TemporaryDirectory

from specify_tool import (
    ROOT, STATE, installed_version, pinned_version, tool_environment, tool_python,
    uv_command, installation_matches, install_signature, signature_path,
)


def update_constraints(command):
    with TemporaryDirectory() as directory:
        source = Path(directory) / "specify.in"
        source.write_text(f"specify-cli=={pinned_version()}\n", encoding="utf-8")
        result = subprocess.run(command + ["pip", "compile", str(source), "--universal",
                                "--python-version", "3.11", "--no-header", "--no-annotate", "--no-emit-package", "specify-cli"],
                                capture_output=True, text=True, encoding="utf-8", errors="replace", check=True)
        (ROOT / "scripts/specify-constraints.txt").write_text(
            "# Generated by bootstrap_specify.py --update-lock; do not edit manually.\n" + result.stdout,
            encoding="utf-8", newline="\n")


def bootstrap(repair=False, update_lock=False):
    version = pinned_version()
    try:
        command = uv_command()
    except ValueError:
        destination = STATE / ("uv-windows" if os.name == "nt" else "uv-posix")
        venv.EnvBuilder(with_pip=False).create(destination)
        python = destination / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
        subprocess.run([sys.executable, "-m", "pip", "--python", str(python), "install", "--disable-pip-version-check",
                        "-r", str(ROOT / "scripts/uv-requirements.txt")], check=True)
        command = uv_command()
    if update_lock:
        update_constraints(command)
    env = tool_environment()
    python = tool_python(command, env)
    if repair or update_lock or not installation_matches(python, env):
        signature_path(env).unlink(missing_ok=True)
        # Relative constraints avoid uv splitting absolute Windows paths with spaces.
        subprocess.run(command + ["tool", "install", "--python", sys.executable,
                                  "--reinstall", "--constraint", "scripts/specify-constraints.txt",
                                  f"specify-cli=={version}"], cwd=ROOT, env=env, check=True)
    if installed_version(python) != version:
        raise ValueError(f"Installation von Spec Kit {version} konnte nicht bestätigt werden.")
    stamp = signature_path(env)
    stamp.parent.mkdir(parents=True, exist_ok=True)
    stamp.write_text(install_signature() + "\n", encoding="utf-8")
    if os.name != "nt":
        (ROOT / "scripts/specify").chmod(0o755)
    print(f"Spec Kit {version}: bereit (Repository-Wrapper).")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repair", action="store_true", help="Tool-Umgebung kontrolliert neu installieren")
    parser.add_argument("--update-lock", action="store_true", help="Transitive Pins für alle Plattformen neu auflösen")
    args = parser.parse_args()
    try:
        bootstrap(args.repair, args.update_lock)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"Specify-Setup fehlgeschlagen: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
